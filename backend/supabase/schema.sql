        'barangay_complaint',
        'barangay_complaintstatuschange'
    ]
    LOOP
        EXECUTE format(
            'ALTER TABLE public.%I ENABLE ROW LEVEL SECURITY',
            table_name
        );

        EXECUTE format(
            'REVOKE ALL ON public.%I
             FROM PUBLIC, anon, authenticated, service_role',
            table_name
        );
    END LOOP;
END;
$lockdown$;


