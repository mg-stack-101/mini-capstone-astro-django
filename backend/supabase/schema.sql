-- =========================================================
-- 6. PRIVATE RLS HELPERS
-- Fixed search_path and fully qualified objects prevent
-- search-path manipulation. Staff status comes from the DB.
-- =========================================================

CREATE FUNCTION barangay_private.current_django_user_id()
RETURNS integer
LANGUAGE sql
STABLE
SECURITY DEFINER
SET search_path = ''
AS $function$
    SELECT account.id
    FROM barangay_private.auth_links AS link
    JOIN public.auth_user AS account
        ON account.id = link.django_user_id
    WHERE link.supabase_user_id = (SELECT auth.uid())
      AND account.is_active;
$function$;

CREATE FUNCTION barangay_private.current_user_is_staff()
RETURNS boolean
LANGUAGE sql
STABLE
SECURITY DEFINER
SET search_path = ''
AS $function$
    SELECT EXISTS (
        SELECT 1
        FROM barangay_private.auth_links AS link
        JOIN public.auth_user AS account
            ON account.id = link.django_user_id
        WHERE link.supabase_user_id = (SELECT auth.uid())
          AND account.is_active
          AND account.is_staff
    );
$function$;

REVOKE ALL
    ON FUNCTION barangay_private.current_django_user_id()
    FROM PUBLIC, anon, service_role;

REVOKE ALL
    ON FUNCTION barangay_private.current_user_is_staff()
    FROM PUBLIC, anon, service_role;

GRANT EXECUTE
    ON FUNCTION barangay_private.current_django_user_id()
    TO authenticated;

GRANT EXECUTE
    ON FUNCTION barangay_private.current_user_is_staff()
    TO authenticated;


