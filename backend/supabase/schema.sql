-- =========================================================
-- 2. COMPLAINTS
-- =========================================================

CREATE TABLE public.barangay_complaint (
    id uuid PRIMARY KEY DEFAULT gen_random_uuid(),

    resident_id integer NOT NULL,
    full_name varchar(150) NOT NULL,
    contact_number varchar(30) NOT NULL,
    address varchar(300) NOT NULL,
    complaint_type varchar(40) NOT NULL,
    description text NOT NULL,

    -- Evidence path only. File validation/storage remains server-side.
    photo varchar(100) NOT NULL,

    status varchar(12) NOT NULL DEFAULT 'Pending',
    created_at timestamptz NOT NULL DEFAULT now(),
    updated_at timestamptz NOT NULL DEFAULT now(),

    CONSTRAINT barangay_complaint_resident_id_33fba601_fk_auth_user_id
        FOREIGN KEY (resident_id)
        REFERENCES public.auth_user(id)
        DEFERRABLE INITIALLY DEFERRED,

    CONSTRAINT valid_complaint_status
        CHECK (status IN ('Pending', 'Processing', 'Resolved')),

    CONSTRAINT sb_complaint_type_check
        CHECK (
            complaint_type IN (
                'Noise Disturbance',
                'Garbage Disposal',
                'Pet Nuisance',
                'Property Dispute',
                'Verbal Altercation',
                'Other'
            )
        ),

    CONSTRAINT sb_complaint_required_text
        CHECK (
            btrim(full_name) <> ''
            AND btrim(contact_number) <> ''
            AND btrim(address) <> ''
            AND btrim(description) <> ''
            AND btrim(photo) <> ''
        ),

    CONSTRAINT sb_complaint_description_length
        CHECK (char_length(description) <= 5000)
);


