-- =========================================================
-- 11. AUTOMATIC AUDIT FOR SUPABASE USER STATUS UPDATES
-- Django DB writes have no auth.uid(); its existing service
-- already creates history, so this avoids duplicate entries.
-- =========================================================

CREATE FUNCTION barangay_private.audit_supabase_status_change()
RETURNS trigger
LANGUAGE plpgsql
SECURITY DEFINER
SET search_path = ''
AS $function$
DECLARE
    actor_id integer;
BEGIN
    IF NEW.status IS DISTINCT FROM OLD.status
       AND (SELECT auth.uid()) IS NOT NULL
    THEN
        actor_id := barangay_private.current_django_user_id();

        IF actor_id IS NULL
           OR NOT barangay_private.current_user_is_staff()
        THEN
            RAISE EXCEPTION
                'A linked active staff account is required.'
                USING ERRCODE = '42501';
        END IF;

        INSERT INTO public.barangay_complaintstatuschange (
            complaint_id,
            changed_by_id,
            from_status,
            to_status,
            created_at
        )
        VALUES (
            NEW.id,
            actor_id,
            OLD.status,
            NEW.status,
            statement_timestamp()
        );
    END IF;

    RETURN NEW;
END;
$function$;

REVOKE ALL
    ON FUNCTION barangay_private.audit_supabase_status_change()
    FROM PUBLIC, anon, authenticated, service_role;

CREATE TRIGGER sb_complaint_status_audit
    AFTER UPDATE OF status
    ON public.barangay_complaint
    FOR EACH ROW
    EXECUTE FUNCTION barangay_private.audit_supabase_status_change();


-- =========================================================
-- 12. PROTECT APPLICATION IDENTITY SEQUENCES
-- Audit inserts run through the trusted definer trigger.
-- =========================================================

DO $sequences$
DECLARE
    sequence_record record;
BEGIN
    FOR sequence_record IN
        SELECT sequence.relname AS sequence_name
        FROM pg_class AS sequence
        JOIN pg_namespace AS namespace
            ON namespace.oid = sequence.relnamespace
        WHERE namespace.nspname = 'public'
          AND sequence.relkind = 'S'
          AND (
              left(sequence.relname, 5) = 'auth_'
              OR left(sequence.relname, 7) = 'django_'
              OR left(sequence.relname, 9) = 'barangay_'
          )
    LOOP
        EXECUTE format(
            'REVOKE ALL ON SEQUENCE public.%I
             FROM PUBLIC, anon, authenticated, service_role',
            sequence_record.sequence_name
        );
    END LOOP;
END;
$sequences$;


