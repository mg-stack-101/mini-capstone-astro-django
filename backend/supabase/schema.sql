-- Trigram search indexes match Django's case-insensitive search expressions.
CREATE SCHEMA IF NOT EXISTS extensions;

CREATE EXTENSION IF NOT EXISTS pg_trgm
    WITH SCHEMA extensions;

DO $indexes$
DECLARE
    extension_schema text;
BEGIN
    SELECT namespace.nspname
    INTO extension_schema
    FROM pg_extension AS extension
    JOIN pg_namespace AS namespace
        ON namespace.oid = extension.extnamespace
    WHERE extension.extname = 'pg_trgm';

    EXECUTE format(
        'CREATE INDEX sb_complaint_name_search_idx
         ON public.barangay_complaint
         USING gin (upper(full_name::text) %I.gin_trgm_ops)',
        extension_schema
    );

    EXECUTE format(
        'CREATE INDEX sb_complaint_type_search_idx
         ON public.barangay_complaint
         USING gin (upper(complaint_type::text) %I.gin_trgm_ops)',
        extension_schema
    );
END;
$indexes$;


