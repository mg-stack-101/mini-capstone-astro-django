-- =========================================================
-- 9. ROW LEVEL SECURITY POLICIES
-- Scalar subqueries let PostgreSQL evaluate identity
-- helpers once per statement rather than once per row.
-- =========================================================

CREATE POLICY sb_complaint_read
    ON public.barangay_complaint
    FOR SELECT
    TO authenticated
    USING (
        resident_id = (
            SELECT barangay_private.current_django_user_id()
        )
        OR (
            SELECT barangay_private.current_user_is_staff()
        )
    );

CREATE POLICY sb_complaint_create_own
    ON public.barangay_complaint
    FOR INSERT
    TO authenticated
    WITH CHECK (
        resident_id = (
            SELECT barangay_private.current_django_user_id()
        )
        AND status = 'Pending'
    );

CREATE POLICY sb_complaint_staff_update
    ON public.barangay_complaint
    FOR UPDATE
    TO authenticated
    USING (
        (SELECT barangay_private.current_user_is_staff())
    )
    WITH CHECK (
        (SELECT barangay_private.current_user_is_staff())
    );

CREATE POLICY sb_history_read
    ON public.barangay_complaintstatuschange
    FOR SELECT
    TO authenticated
    USING (
        EXISTS (
            SELECT 1
            FROM public.barangay_complaint AS complaint
            WHERE complaint.id =
                barangay_complaintstatuschange.complaint_id
        )
    );


